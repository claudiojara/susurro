@testable import TextInsertion

/// One type of a pasteboard item with its data.
struct PasteboardEntry: Equatable {
    let type: String
    let data: Data
}

/// A pasteboard of its own and the clock an inserter runs on, shared by the suites that test the inserter.
@MainActor
final class PasteFixture {
    /// A pasteboard of its own, so the tests never touch the user's clipboard.
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("susurro-test-\(UUID().uuidString)"))
    /// The inserter's clock. It moves when the inserter sleeps.
    let clock = SteppedClock()

    isolated deinit {
        pasteboard.releaseGlobally()
    }

    func makeInserter(
        _ keys: FakeKeystrokePoster,
        sourceBundleID: String,
        writeItem: ((NSPasteboard, NSPasteboardItem) -> Bool)?
    ) -> SimplePasteInserter {
        guard let writeItem else {
            return SimplePasteInserter(
                pasteboard: pasteboard, keystrokes: keys, clock: clock, sourceBundleID: sourceBundleID)
        }
        return SimplePasteInserter(
            pasteboard: pasteboard,
            keystrokes: keys,
            clock: clock,
            sourceBundleID: sourceBundleID,
            writeItem: writeItem
        )
    }

    /// Reads the text the way an app that pastes it does. For a promised text this is the read that counts as a receipt.
    func readAsApp() -> String? {
        pasteboard.string(forType: .string)
    }

    /// Two items, as a copied rich selection leaves them: text with RTF and an image, and a second text.
    func putRichContent(rtf: Data, png: Data) {
        pasteboard.clearContents()
        let first = NSPasteboardItem()
        first.setString("alpha", forType: .string)
        first.setData(rtf, forType: .rtf)
        first.setData(png, forType: .png)
        let second = NSPasteboardItem()
        second.setString("beta", forType: .string)
        _ = pasteboard.writeObjects([first, second])
    }

    /// Every item with its types in order and the data of each. Reading the data of a promised type counts as a read,
    /// so this is for pasteboards without a promise, or after the read.
    func contents() -> [[PasteboardEntry]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { PasteboardEntry(type: type.rawValue, data: $0) }
            }
        }
    }

    /// The types the first item declares. Declaring a type does not read its data.
    func declaredTypes() -> Set<String> {
        Set(pasteboard.pasteboardItems?.first?.types.map(\.rawValue) ?? [])
    }
}

/// What a suite that tests the inserter gets from its fixture. The members forward to it, so the tests read plainly.
@MainActor
protocol PasteTestCase {
    var fixture: PasteFixture { get }
}

extension PasteTestCase {
    // The timings, spelled out once. The quiet period (200 ms) and the receipt timeout (8 s) are the spec's; the
    // modifier timeout (500 ms), the minimum dwell (1 s), and the two poll intervals come from the tasks and the review.
    // They are not read from `PasteTiming`, so changing a constant there fails these tests.
    static var restoreDelay: Duration { .milliseconds(200) }
    static var minimumDwell: Duration { .seconds(1) }
    static var modifierTimeout: Duration { .milliseconds(500) }
    static var receiptTimeout: Duration { .seconds(8) }
    static var modifierPollInterval: Duration { .milliseconds(20) }
    static var receiptPollInterval: Duration { .milliseconds(50) }

    static var sourceBundleID: String { "dev.example.source" }
    static var markerTypes: Set<String> {
        [
            "org.nspasteboard.TransientType",
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.AutoGeneratedType",
            "org.nspasteboard.source",
        ]
    }
    static var rtf: Data { Data("{\\rtf1 rich}".utf8) }
    static var png: Data { Data([0x89, 0x50, 0x4E, 0x47]) }

    typealias Entry = PasteboardEntry

    var pasteboard: NSPasteboard { fixture.pasteboard }
    var clock: SteppedClock { fixture.clock }

    /// Every pause the inserter asked for, in order.
    var sleeps: [Duration] { clock.sleeps }
    /// The pauses that ran to the end, as opposed to those that were cancelled.
    var completedSleeps: [Duration] { clock.completedSleeps }
    /// Runs when the inserter pauses, standing in for whatever happens meanwhile. It may throw to cancel the pause.
    var onSleep: SteppedClock.SleepHook? {
        get { nil }
        nonmutating set { clock.setHook(newValue) }
    }

    func makeInserter(
        _ keys: FakeKeystrokePoster = FakeKeystrokePoster(),
        writeItem: ((NSPasteboard, NSPasteboardItem) -> Bool)? = nil
    ) -> SimplePasteInserter {
        fixture.makeInserter(keys, sourceBundleID: Self.sourceBundleID, writeItem: writeItem)
    }

    /// A target app that reads the text as soon as it receives the chord.
    func appReadsOnPaste(_ keys: FakeKeystrokePoster) {
        keys.onPost = { [fixture] in _ = fixture.readAsApp() }
    }

    func putRichContent() { fixture.putRichContent(rtf: Self.rtf, png: Self.png) }
    func contents() -> [[Entry]] { fixture.contents() }
    func declaredTypes() -> Set<String> { fixture.declaredTypes() }

    /// Whether the text is still on the pasteboard as a promise, which is marked as transient.
    func isTextPromised() -> Bool { declaredTypes().contains("org.nspasteboard.TransientType") }

    /// The text on the pasteboard, read the way an app reads it.
    var pasteboardText: String? { fixture.readAsApp() }

    /// Checks that the text was left alone on the pasteboard as plain text under the markers, with no restore.
    func expectMarkedTextLeft(_ text: String, sourceLocation: SourceLocation = #_sourceLocation) {
        #expect(pasteboardText == text, sourceLocation: sourceLocation)
        #expect(contents().count == 1, sourceLocation: sourceLocation)
        #expect(declaredTypes().isSuperset(of: Self.markerTypes), sourceLocation: sourceLocation)
    }
}
