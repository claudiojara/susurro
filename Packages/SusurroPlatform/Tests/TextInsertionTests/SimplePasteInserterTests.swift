import AppKit
import CoreTestSupport
import Domain
import Testing

@testable import TextInsertion

@MainActor
@Suite("Simple paste inserter", .timeLimit(.minutes(1)))
final class SimplePasteInserterTests {
    // The timings, spelled out once. The quiet period (200 ms) and the receipt timeout (8 s) are the spec's; the
    // modifier timeout (500 ms), the minimum dwell (1 s), and the two poll intervals come from the tasks and the review.
    // They are not read from `PasteTiming`, so changing a constant there fails these tests.
    private static let restoreDelay = Duration.milliseconds(200)
    private static let minimumDwell = Duration.seconds(1)
    private static let modifierTimeout = Duration.milliseconds(500)
    private static let receiptTimeout = Duration.seconds(8)
    private static let modifierPollInterval = Duration.milliseconds(20)
    private static let receiptPollInterval = Duration.milliseconds(50)

    private static let sourceBundleID = "dev.example.source"
    private static let markerTypes: Set = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.source",
    ]
    private static let rtf = Data("{\\rtf1 rich}".utf8)
    private static let png = Data([0x89, 0x50, 0x4E, 0x47])

    /// One type of a pasteboard item with its data.
    private struct Entry: Equatable {
        let type: String
        let data: Data
    }

    /// A pasteboard of its own, so the tests never touch the user's clipboard.
    private let pasteboard = NSPasteboard(name: NSPasteboard.Name("susurro-test-\(UUID().uuidString)"))
    /// The inserter's clock. It moves when the inserter sleeps.
    private let clock = SteppedClock()

    /// Every pause the inserter asked for, in order.
    private var sleeps: [Duration] { clock.sleeps }
    /// The pauses that ran to the end, as opposed to those that were cancelled.
    private var completedSleeps: [Duration] { clock.completedSleeps }
    /// Runs when the inserter pauses, standing in for whatever happens meanwhile. It may throw to cancel the pause.
    private var onSleep: SteppedClock.SleepHook? {
        get { nil }
        set { clock.setHook(newValue) }
    }

    isolated deinit {
        pasteboard.releaseGlobally()
    }

    private func makeInserter(
        _ keys: FakeKeystrokePoster = FakeKeystrokePoster(),
        writeItem: ((NSPasteboard, NSPasteboardItem) -> Bool)? = nil
    ) -> SimplePasteInserter {
        guard let writeItem else {
            return SimplePasteInserter(
                pasteboard: pasteboard,
                keystrokes: keys,
                clock: clock,
                sourceBundleID: Self.sourceBundleID
            )
        }
        return SimplePasteInserter(
            pasteboard: pasteboard,
            keystrokes: keys,
            clock: clock,
            sourceBundleID: Self.sourceBundleID,
            writeItem: writeItem
        )
    }

    /// A target app that reads the text as soon as it receives the chord.
    private func readOnPost(_ keys: FakeKeystrokePoster) {
        keys.onPost = { [pasteboard] in _ = pasteboard.string(forType: .string) }
    }

    /// Two items, as a copied rich selection leaves them: text with RTF and an image, and a second text.
    private func putRichContent() {
        pasteboard.clearContents()
        let first = NSPasteboardItem()
        first.setString("alpha", forType: .string)
        first.setData(Self.rtf, forType: .rtf)
        first.setData(Self.png, forType: .png)
        let second = NSPasteboardItem()
        second.setString("beta", forType: .string)
        _ = pasteboard.writeObjects([first, second])
    }

    /// Every item with its types in order and the data of each. Reading the data of a promised type counts as a read,
    /// so this is for pasteboards without a promise, or after the read.
    private func contents() -> [[Entry]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { Entry(type: type.rawValue, data: $0) } }
        }
    }

    /// The types the first item declares. Declaring a type does not read its data.
    private func declaredTypes() -> Set<String> {
        Set(pasteboard.pasteboardItems?.first?.types.map(\.rawValue) ?? [])
    }

    private var pasteboardText: String? { pasteboard.string(forType: .string) }

    // MARK: Paste and restore

    @Test("the text is on the pasteboard when the chord is posted, and the rich pasteboard is back after 300 ms")
    func pastesAndRestores() async throws {
        putRichContent()
        let before = contents()
        let first = try #require(before.first)
        #expect(before.count == 2)
        #expect(first.first { $0.type == NSPasteboard.PasteboardType.rtf.rawValue }?.data == Self.rtf)
        #expect(first.first { $0.type == NSPasteboard.PasteboardType.png.rawValue }?.data == Self.png)
        let keys = FakeKeystrokePoster()
        var textWhenPosted: String?
        var textDuringDelay: String?
        keys.onPost = { [pasteboard] in textWhenPosted = pasteboard.string(forType: .string) }
        onSleep = { [pasteboard] _ in textDuringDelay = pasteboard.string(forType: .string) }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(textWhenPosted == "hello world")
        #expect(textDuringDelay == "hello world")
        #expect(clock.elapsed == Self.minimumDwell)
        #expect(keys.postCount == 1)
        #expect(contents() == before)
    }

    @Test("an empty pasteboard is empty again after the paste")
    func emptyPasteboardIsRestored() async {
        pasteboard.clearContents()
        let keys = FakeKeystrokePoster()
        var textWhenPosted: String?
        keys.onPost = { [pasteboard] in textWhenPosted = pasteboard.string(forType: .string) }

        let outcome = await makeInserter(keys).insert("dictated")

        #expect(outcome == .inserted)
        #expect(textWhenPosted == "dictated")
        #expect(pasteboardText == nil)
        #expect(contents().isEmpty)
    }

    @Test("a copy by the user after the read is not overwritten")
    func userCopyWins() async {
        putRichContent()
        let keys = FakeKeystrokePoster()
        readOnPost(keys)
        onSleep = { [pasteboard] _ in
            pasteboard.clearContents()
            pasteboard.setString("user copy", forType: .string)
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(pasteboardText == "user copy")
        #expect(contents().count == 1)
    }

    @Test("two dictations in a row each restore the original pasteboard")
    func sequentialInsertions() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        var texts: [String?] = []
        keys.onPost = { [pasteboard] in texts.append(pasteboard.string(forType: .string)) }
        let sut = makeInserter(keys)

        let first = await sut.insert("one")
        let afterFirst = contents()
        let second = await sut.insert("two")

        #expect([first, second] == [.inserted, .inserted])
        #expect(texts == ["one", "two"])
        #expect(afterFirst == before)
        #expect(contents() == before)
    }

    // MARK: Read receipt

    @Test("the text is promised under the markers, and it is provided only when an app reads it")
    func promisedUnderMarkers() async {
        putRichContent()
        let keys = FakeKeystrokePoster()
        var typesBeforeRead: Set<String> = []
        var itemCount = 0
        var source: String?
        var textWhenRead: String?
        keys.onPost = { [pasteboard] in
            typesBeforeRead = Set(pasteboard.pasteboardItems?.first?.types.map(\.rawValue) ?? [])
            itemCount = pasteboard.pasteboardItems?.count ?? 0
            source = pasteboard.pasteboardItems?.first?.string(
                forType: NSPasteboard.PasteboardType("org.nspasteboard.source")
            )
            textWhenRead = pasteboard.string(forType: .string)
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(typesBeforeRead == Self.markerTypes.union(["public.utf8-plain-text"]))
        #expect(itemCount == 1)
        #expect(source == Self.sourceBundleID)
        #expect(textWhenRead == "hello world")
        #expect(outcome == .inserted)
    }

    @Test("the rich pasteboard stays replaced until an app has read the text")
    func restoredOnlyAfterTheRead() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        var polls = 0
        var promisedWhilePolling: [Bool] = []
        onSleep = { [pasteboard] duration in
            guard duration == Self.receiptPollInterval else { return }
            polls += 1
            if polls < 5 {
                let types = pasteboard.pasteboardItems?.first?.types.map(\.rawValue) ?? []
                promisedWhilePolling.append(types.contains("org.nspasteboard.TransientType"))
            } else {
                _ = pasteboard.string(forType: .string)  // the app reads on the fifth poll
            }
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(promisedWhilePolling == [true, true, true, true])
        #expect(clock.elapsed == Self.minimumDwell)
        #expect(contents() == before)
    }

    @Test("with no read for 8 seconds the marked text stays on the pasteboard, with no restore")
    func noReadTimesOut() async {
        putRichContent()
        let keys = FakeKeystrokePoster()

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(keys.postCount == 1)
        #expect(sleeps.reduce(.zero, +) == Self.receiptTimeout)
        #expect(pasteboardText == "hello world")
        #expect(contents().count == 1)
        #expect(declaredTypes().isSuperset(of: Self.markerTypes))
    }

    @Test("a caller cancelled after the chord was posted still gets the paste finished and the pasteboard restored")
    func cancelledAfterTheChord() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        var caller: Task<InsertionOutcome, Never>?
        keys.onPost = { [pasteboard] in
            _ = pasteboard.string(forType: .string)
            caller?.cancel()
        }
        let sut = makeInserter(keys)

        caller = Task { await sut.insert("hello world") }
        let outcome = await caller?.value

        #expect(outcome == .inserted)
        #expect(completedSleeps.reduce(.zero, +) == Self.minimumDwell)
        #expect(contents() == before)
    }

    @Test("the old pasteboard is not restored before the minimum dwell after the chord")
    func noRestoreBeforeTheMinimumDwell() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        readOnPost(keys)
        var promisedAtEveryPause: [Bool] = []
        onSleep = { [pasteboard] _ in
            let types = pasteboard.pasteboardItems?.first?.types.map(\.rawValue) ?? []
            promisedAtEveryPause.append(types.contains("org.nspasteboard.TransientType"))
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(promisedAtEveryPause == Array(repeating: true, count: 20))  // one pause per 50 ms, up to 1 s
        #expect(clock.elapsed == Self.minimumDwell)
        #expect(contents() == before)
    }

    @Test("the old pasteboard comes back 200 ms after the last read, when that is later than the minimum dwell")
    func quietPeriodAfterALateRead() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        var pauses = 0
        onSleep = { [pasteboard] _ in
            pauses += 1
            if pauses == 19 { _ = pasteboard.string(forType: .string) }  // the app reads at 950 ms
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(clock.elapsed == Duration.milliseconds(950) + Self.restoreDelay)
        #expect(contents() == before)
    }

    @Test("a read before the chord is not a receipt, so the paste counts as failed and the text is left")
    func readBeforeTheChordIsNotAReceipt() async {
        putRichContent()
        let keys = FakeKeystrokePoster()
        // A clipboard manager that ignores the markers reads the text as soon as it is written. The pasteboard then
        // serves every later read from its cache, so the app's own read cannot be seen either.
        let sut = makeInserter(
            keys,
            writeItem: { pasteboard, item in
                let accepted = pasteboard.writeObjects([item])
                _ = pasteboard.string(forType: .string)
                return accepted
            }
        )

        let outcome = await sut.insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(keys.postCount == 1)
        #expect(clock.elapsed == Self.receiptTimeout)
        #expect(pasteboardText == "hello world")
        #expect(contents().count == 1)
    }

    // MARK: Safety

    @Test("empty text leaves the pasteboard and its change count alone")
    func emptyText() async {
        putRichContent()
        let before = contents()
        let changeCount = pasteboard.changeCount
        let keys = FakeKeystrokePoster()

        let outcome = await makeInserter(keys).insert("")

        #expect(outcome == .inserted)
        #expect(pasteboard.changeCount == changeCount)
        #expect(contents() == before)
        #expect(keys.calls.isEmpty)
        #expect(sleeps.isEmpty)
    }

    @Test(
        "when the chord cannot be posted the marked text stays on the pasteboard, with no restore",
        arguments: [
            (KeystrokeError.accessibilityNotGranted, InsertionOutcome.copiedToClipboard(.accessibilityMissing)),
            (.eventCreationFailed, .copiedToClipboard(.pasteFailed)),
        ]
    )
    func chordNotPosted(failure: KeystrokeError, expected: InsertionOutcome) async {
        putRichContent()
        let keys = FakeKeystrokePoster(postFailure: failure)

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == expected)
        #expect(pasteboardText == "hello world")
        #expect(contents().count == 1)
        #expect(declaredTypes().isSuperset(of: Self.markerTypes))
        #expect(sleeps.isEmpty)
    }

    @Test("a modifier still held is waited for, polling at a fixed interval, before the chord")
    func waitsForModifiers() async {
        let keys = FakeKeystrokePoster(modifiersHeldFor: 3)
        readOnPost(keys)

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(keys.calls == [.modifiersHeld, .modifiersHeld, .modifiersHeld, .modifiersHeld, .postPaste])
        #expect(Array(sleeps.prefix(3)) == Array(repeating: Self.modifierPollInterval, count: 3))
        #expect(clock.elapsed == Self.modifierPollInterval * 3 + Self.minimumDwell)
    }

    @Test("while a modifier is held the user's pasteboard is untouched, and it is back at the end")
    func pasteboardUntouchedWhileWaiting() async {
        putRichContent()
        let before = contents()
        let changeCount = pasteboard.changeCount
        let keys = FakeKeystrokePoster(modifiersHeldFor: 3)
        readOnPost(keys)
        var seenDuringWait: [[[Entry]]] = []
        var changeCountsDuringWait: [Int] = []
        onSleep = { [unowned self] duration in
            guard duration == Self.modifierPollInterval else { return }
            seenDuringWait.append(contents())
            changeCountsDuringWait.append(pasteboard.changeCount)
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .inserted)
        #expect(seenDuringWait == Array(repeating: before, count: 3))
        #expect(changeCountsDuringWait == Array(repeating: changeCount, count: 3))
        #expect(contents() == before)
    }

    /// When a modifier that is held is let go, in terms of the polls the inserter is allowed.
    enum Release {
        case atLastPoll
        case onePollLate
        case never
    }

    @Test(
        "modifiers are waited for up to 500 ms; past that no chord is posted and the marked text stays",
        arguments: [Release.atLastPoll, .onePollLate, .never]
    )
    func modifiersTimeout(release: Release) async {
        putRichContent()
        let allowedPolls = Int(Self.modifierTimeout / Self.modifierPollInterval)
        let heldFor =
            switch release {
            case .atLastPoll: allowedPolls
            case .onePollLate: allowedPolls + 1
            case .never: allowedPolls * 10
            }
        let keys = FakeKeystrokePoster(modifiersHeldFor: heldFor)
        readOnPost(keys)

        let outcome = await makeInserter(keys).insert("hello world")

        let waited = sleeps.filter { $0 == Self.modifierPollInterval }.reduce(.zero, +)
        #expect(waited == Self.modifierTimeout)
        if release == .atLastPoll {
            #expect(keys.postCount == 1)
            #expect(outcome == .inserted)
            #expect(clock.elapsed == Self.modifierTimeout + Self.minimumDwell)
            #expect(contents().count == 2)
        } else {
            #expect(keys.postCount == 0)
            #expect(outcome == .copiedToClipboard(.pasteFailed))
            #expect(pasteboardText == "hello world")
            #expect(contents().count == 1)
            #expect(declaredTypes().isSuperset(of: Self.markerTypes))
            #expect(clock.elapsed == Self.modifierTimeout)
        }
    }

    @Test("a wait for modifiers that is cancelled writes nothing and posts no chord", arguments: [1, 3])
    func cancelledWhileWaitingForModifiers(cancelledPoll: Int) async {
        putRichContent()
        let before = contents()
        let changeCount = pasteboard.changeCount
        let keys = FakeKeystrokePoster(modifiersHeldFor: 5)
        var polls = 0
        onSleep = { _ in
            polls += 1
            if polls == cancelledPoll { throw CancellationError() }
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(polls == cancelledPoll)
        #expect(keys.postCount == 0)
        #expect(pasteboard.changeCount == changeCount)
        #expect(contents() == before)
    }

    @Test("a write that the pasteboard refuses posts no chord and gives the old contents back")
    func refusedWrite() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()

        let outcome = await makeInserter(keys, writeItem: { _, _ in false }).insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(keys.postCount == 0)
        #expect(contents() == before)
    }

    // MARK: Overlap and cancellation

    @Test(
        "a second insertion started while the first waits for its read does not take the first text for the pasteboard")
    func secondInsertionWaitsForTheFirst() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        var textsWhenPosted: [String?] = []
        keys.onPost = { [pasteboard] in textsWhenPosted.append(pasteboard.string(forType: .string)) }
        let sut = makeInserter(keys)
        var second: Task<InsertionOutcome, Never>?
        onSleep = { _ in
            if second == nil { second = Task { await sut.insert("two") } }  // the first is still waiting out its dwell
        }

        let first = await sut.insert("one")
        let secondOutcome = await second?.value

        #expect([first, secondOutcome] == [.inserted, .inserted])
        #expect(textsWhenPosted == ["one", "two"])
        #expect(contents() == before)
    }

    @Test("a second insertion does not wait for ever for a first one that is stuck")
    func waitForTheFirstIsBounded() async {
        putRichContent()
        let keys = FakeKeystrokePoster()
        var postedAt: [Duration] = []
        keys.onPost = { [clock] in postedAt.append(clock.elapsed) }
        let sut = makeInserter(keys)
        let stuck = clock.suspendNextSleep()

        let first = Task { await sut.insert("one") }
        await stuck.entered.wait()
        let secondOutcome = await sut.insert("two")
        stuck.release.open()
        _ = await first.value

        #expect(secondOutcome == .copiedToClipboard(.pasteFailed))
        #expect(postedAt.count == 2)
        #expect(postedAt.last.map { $0 >= Self.modifierTimeout + Self.receiptTimeout + Self.restoreDelay } == true)
    }

    @Test("a caller cancelled once the modifiers are up writes nothing")
    func cancelledBeforeTheWrite() async {
        putRichContent()
        let before = contents()
        let changeCount = pasteboard.changeCount
        let keys = FakeKeystrokePoster(modifiersHeldFor: 1)
        let sut = makeInserter(keys)
        var caller: Task<InsertionOutcome, Never>?
        onSleep = { _ in caller?.cancel() }  // the wait itself is not cut short, the task is only marked as cancelled

        caller = Task { await sut.insert("hello world") }
        let outcome = await caller?.value

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(keys.postCount == 0)
        #expect(pasteboard.changeCount == changeCount)
        #expect(contents() == before)
    }

    @Test("a caller cancelled after the write posts no chord and gives the old contents back")
    func cancelledBeforeTheChord() async {
        putRichContent()
        let before = contents()
        let keys = FakeKeystrokePoster()
        var caller: Task<InsertionOutcome, Never>?
        let sut = makeInserter(
            keys,
            writeItem: { pasteboard, item in
                let accepted = pasteboard.writeObjects([item])
                caller?.cancel()
                return accepted
            }
        )

        caller = Task { await sut.insert("hello world") }
        let outcome = await caller?.value

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(keys.postCount == 0)
        #expect(contents() == before)
    }

    @Test("a copy by the user while the paste waits for a read is not overwritten when the wait ends")
    func userCopyDuringTheWaitWinsOverTheFallback() async {
        putRichContent()
        let keys = FakeKeystrokePoster()
        var pauses = 0
        onSleep = { [pasteboard] _ in
            pauses += 1
            if pauses == 3 {
                pasteboard.clearContents()
                pasteboard.setString("user copy", forType: .string)
            }
        }

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(clock.elapsed == Self.receiptTimeout)
        #expect(pasteboardText == "user copy")
        #expect(contents().count == 1)
    }

    // MARK: Wall-clock deadlines

    @Test("the wait for modifiers ends by the clock, not by the number of pauses")
    func modifierWaitFollowsTheClock() async {
        putRichContent()
        let keys = FakeKeystrokePoster(modifiersHeldFor: 1_000)
        onSleep = { [clock] _ in clock.advance(by: .seconds(2)) }  // the main actor was busy for 2 s

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(sleeps == [Self.modifierPollInterval])
        #expect(keys.postCount == 0)
        #expect(pasteboardText == "hello world")
    }

    @Test("the wait for a read ends by the clock, not by the number of pauses")
    func receiptWaitFollowsTheClock() async {
        putRichContent()
        let keys = FakeKeystrokePoster()
        onSleep = { [clock] _ in clock.advance(by: .seconds(9)) }  // the main actor was busy for 9 s

        let outcome = await makeInserter(keys).insert("hello world")

        #expect(outcome == .copiedToClipboard(.pasteFailed))
        #expect(sleeps == [Self.receiptPollInterval])
        #expect(pasteboardText == "hello world")
        #expect(contents().count == 1)
    }
}
