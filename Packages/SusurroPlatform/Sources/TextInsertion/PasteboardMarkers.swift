import AppKit

extension NSPasteboard.PasteboardType {
    // The types that clipboard managers agree to look for (nspasteboard.org). Their presence is the signal; their data
    // is empty.
    static let transientMarker = Self("org.nspasteboard.TransientType")
    static let concealedMarker = Self("org.nspasteboard.ConcealedType")
    static let autoGeneratedMarker = Self("org.nspasteboard.AutoGeneratedType")
    /// The bundle identifier of the app that wrote the item.
    static let sourceApp = Self("org.nspasteboard.source")
}

extension NSPasteboardItem {
    /// An item that asks clipboard managers not to record it, with its content set by `content`. Nil if the item
    /// refuses a type.
    static func marked(source: String, content: (NSPasteboardItem) -> Bool) -> NSPasteboardItem? {
        let item = NSPasteboardItem()
        let markers: [NSPasteboard.PasteboardType] = [.transientMarker, .concealedMarker, .autoGeneratedMarker]
        guard markers.allSatisfy({ item.setData(Data(), forType: $0) }),
            item.setString(source, forType: .sourceApp),
            content(item)
        else { return nil }
        return item
    }
}
